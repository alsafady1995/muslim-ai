language plpgsql security definer set search_path = public as $$
declare v_owner uuid := public._khatma_require_owner(p_group);
begin
  if p_user = v_owner then raise exception 'community:cannot_remove_self' using errcode = '22023'; end if;
  delete from public.khatma_members where group_id = p_group and user_id = p_user;
  if p_ban then
    insert into public.khatma_bans (group_id, user_id) values (p_group, p_user) on conflict do nothing;
  end if;
end $$;

-- Groups I belong to, with progress of the current khatma and the calls I haven't answered.
create or replace function public.get_my_khatma_groups() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(x order by x ->> 'last_activity' desc), '[]'::jsonb) from (
    select jsonb_build_object(
      'id', g.id, 'name', g.name, 'round', g.round, 'khatmas_completed', g.khatmas_completed,
      'role', m.role, 'muted', m.muted,
      'round_reason', g.round_reason, 'round_dedication', g.round_dedication,
      'member_count', (select count(*) from public.khatma_members mm where mm.group_id = g.id),
      'done_count', (select count(*) from public.khatma_parts p where p.group_id = g.id and p.round = g.round and p.done_at is not null),
      'my_juz', coalesce((select jsonb_agg(p.juz order by p.juz) from public.khatma_parts p
                          where p.group_id = g.id and p.round = g.round and p.assignee = m.user_id and p.done_at is null), '[]'::jsonb),
      'open_calls', (select count(*) from public.group_calls c
                     where c.group_id = g.id and c.expires_at > now() and c.kind <> 'khatma_done'
                       and c.sender_id is distinct from m.user_id
                       and not exists (select 1 from public.group_call_responses r where r.call_id = c.id and r.user_id = m.user_id)),
      'last_activity', greatest(g.created_at, m.joined_at,
                                (select max(c.created_at) from public.group_calls c where c.group_id = g.id),
                                (select max(p.done_at) from public.khatma_parts p where p.group_id = g.id))
    ) as x
    from public.khatma_members m join public.khatma_groups g on g.id = m.group_id
    where m.user_id = auth.uid()
  ) s
$$;

-- ---------------------------------------------------------------------------
-- RPCs: dividing and finishing juz'
-- ---------------------------------------------------------------------------
create or replace function public._khatma_part_for_update(p_group uuid, p_juz int) returns public.khatma_parts
language plpgsql security definer set search_path = public as $$
declare v_part public.khatma_parts;
begin
  select p.* into v_part from public.khatma_parts p join public.khatma_groups g on g.id = p.group_id
  where p.group_id = p_group and p.round = g.round and p.juz = p_juz for update of p;
  if v_part.group_id is null then raise exception 'community:invalid_juz' using errcode = '22023'; end if;
  return v_part;
end $$;

create or replace function public.claim_khatma_juz(p_group uuid, p_juz int) returns void
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._khatma_require_member(p_group); v_part public.khatma_parts;
begin
  v_part := public._khatma_part_for_update(p_group, p_juz);
  if v_part.done_at is not null or (v_part.assignee is not null and v_part.assignee <> v_user) then
    raise exception 'community:juz_taken' using errcode = '22023';
  end if;
  update public.khatma_parts set assignee = v_user, assigned_at = now()
  where group_id = v_part.group_id and round = v_part.round and juz = v_part.juz;
end $$;

-- Owner assigns a juz' to a member (or clears it with p_user = null).
create or replace function public.assign_khatma_juz(p_group uuid, p_juz int, p_user uuid) returns void
language plpgsql security definer set search_path = public as $$
declare v_owner uuid := public._khatma_require_owner(p_group); v_part public.khatma_parts;
begin
  if p_user is not null and public._khatma_role(p_group, p_user) is null then
    raise exception 'community:not_member' using errcode = '22023';
  end if;
  v_part := public._khatma_part_for_update(p_group, p_juz);
  if v_part.done_at is not null then raise exception 'community:juz_taken' using errcode = '22023'; end if;
  update public.khatma_parts set assignee = p_user, assigned_at = case when p_user is null then null else now() end
  where group_id = v_part.group_id and round = v_part.round and juz = v_part.juz;
end $$;

-- The assignee gives a juz' back; the owner can release anyone's.
create or replace function public.release_khatma_juz(p_group uuid, p_juz int) returns void
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._khatma_require_member(p_group); v_part public.khatma_parts;
begin
  v_part := public._khatma_part_for_update(p_group, p_juz);
  if v_part.done_at is not null then raise exception 'community:juz_taken' using errcode = '22023'; end if;
  if v_part.assignee is distinct from v_user and public._khatma_role(p_group, v_user) <> 'owner' then
    raise exception 'community:not_owner' using errcode = '42501';
  end if;
  update public.khatma_parts set assignee = null, assigned_at = null
  where group_id = v_part.group_id and round = v_part.round and juz = v_part.juz;
end $$;

-- Owner shares every open juz' among the members, fewest-assigned first.
create or replace function public.distribute_khatma_juz(p_group uuid) returns int
language plpgsql security definer set search_path = public as $$
declare
  v_owner uuid := public._khatma_require_owner(p_group);
  v_round int;
  v_part record;
  v_user uuid;
  v_count int := 0;
begin
  select round into v_round from public.khatma_groups where id = p_group for update;
  for v_part in
    select juz from public.khatma_parts where group_id = p_group and round = v_round and assignee is null and done_at is null order by juz
  loop
    select m.user_id into v_user
    from public.khatma_members m
    left join public.khatma_parts p on p.group_id = m.group_id and p.round = v_round and p.assignee = m.user_id and p.done_at is null
    where m.group_id = p_group
    group by m.user_id, m.joined_at
    order by count(p.juz), m.joined_at, m.user_id
    limit 1;
    update public.khatma_parts set assignee = v_user, assigned_at = now()
    where group_id = p_group and round = v_round and juz = v_part.juz;
    v_count := v_count + 1;
  end loop;
  return v_count;
end $$;

-- Mark a juz' as read. An open juz' is taken by whoever finishes it. When all 30 are done the
-- khatma is complete: the group starts the next round and a 'khatma_done' call is posted (the app
-- asks the push function to announce it, with the call id returned here).
create or replace function public.complete_khatma_juz(p_group uuid, p_juz int) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_user uuid := public._khatma_require_member(p_group);
  v_part public.khatma_parts;
  v_left int;
  v_group public.khatma_groups;
  v_call bigint;
begin
  select * into v_group from public.khatma_groups where id = p_group for update;
  v_part := public._khatma_part_for_update(p_group, p_juz);
  if v_part.done_at is not null then return jsonb_build_object('khatma_completed', false, 'duplicate', true); end if;
  if v_part.assignee is not null and v_part.assignee <> v_user then
    raise exception 'community:juz_taken' using errcode = '22023';
  end if;
  update public.khatma_parts set assignee = v_user, assigned_at = coalesce(assigned_at, now()), done_by = v_user, done_at = now()
  where group_id = p_group and round = v_part.round and juz = p_juz;

  select count(*) into v_left from public.khatma_parts where group_id = p_group and round = v_group.round and done_at is null;
  if v_left = 0 then
    update public.khatma_groups set round = round + 1, khatmas_completed = khatmas_completed + 1,
      round_reason = null, round_dedication = null
    where id = p_group;
    insert into public.khatma_parts (group_id, round, juz) select p_group, v_group.round + 1, g from generate_series(1, 30) g;
    insert into public.group_calls (group_id, sender_id, kind, reason, dedication, round, expires_at)
    values (p_group, null, 'khatma_done', v_group.round_reason, v_group.round_dedication, v_group.round, now() + interval '3 days')
    returning id into v_call;
    return jsonb_build_object('khatma_completed', true, 'number', v_group.khatmas_completed + 1, 'call_id', v_call);
  end if;
  return jsonb_build_object('khatma_completed', false, 'left', v_left);
end $$;

-- Undo a mis-tap (whoever finished it, or the owner), current round only.
create or replace function public.uncomplete_khatma_juz(p_group uuid, p_juz int) returns void
language plpgsql security definer set search_path = public as $$
declare v_user uuid := public._khatma_require_member(p_group); v_part public.khatma_parts;
begin
  v_part := public._khatma_part_for_update(p_group, p_juz);
  if v_part.done_at is null then return; end if;
  if v_part.done_by is distinct from v_user and public._khatma_role(p_group, v_user) <> 'owner' then
    raise exception 'community:not_owner' using errcode = '42501';
  end if;
  update public.khatma_parts set done_at = null, done_by = null
  where group_id = p_group and round = v_part.round and juz = p_juz;
end $$;

-- ---------------------------------------------------------------------------
-- RPCs: preset calls
-- ---------------------------------------------------------------------------
-- Send a call to the group. Returns the call id; the app then asks the group-push function to
-- notify the other members. Limits: the same kind at most once per 30 minutes per group, and 10
-- calls a day per sender.
create or replace function public.send_group_call(p_group uuid, p_kind text, p_reason text default null,
                                                  p_dedication text default null) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_user uuid := public._khatma_require_member(p_group);
  v_reason text;
  v_dedication text;
  v_group public.khatma_groups;
  v_id bigint;
begin
  if p_kind is null or p_kind not in ('khatma', 'salawat', 'istighfar', 'adhkar_morning', 'adhkar_evening', 'dua') then
    raise exception 'community:invalid_call' using errcode = '22023';
  end if;
  -- A reason (and an optional name) only for a khatma or a dua.
  if p_kind in ('khatma', 'dua') then
    v_reason := coalesce(nullif(btrim(coalesce(p_reason, '')), ''), 'general');
    if not public._group_reason_ok(v_reason) then raise exception 'community:invalid_call' using errcode = '22023'; end if;
    if v_reason <> 'general' then v_dedication := public._community_optional_text(p_dedication, 30); end if;
  end if;

  select * into v_group from public.khatma_groups where id = p_group for update;
  if exists (select 1 from public.group_calls where group_id = p_group and kind = p_kind
             and created_at > now() - interval '30 minutes') then
    raise exception 'community:call_too_soon' using errcode = '22023';
  end if;
  if (select count(*) from public.group_calls where sender_id = v_user and created_at > now() - interval '1 day') >= 10 then
    raise exception 'community:slow_down' using errcode = '22023';
  end if;

  if p_kind = 'khatma' then
    -- The call gives the current khatma its intention, as long as nobody has finished a juz' of it yet.
    if exists (select 1 from public.khatma_parts where group_id = p_group and round = v_group.round and done_at is not null) then
      raise exception 'community:khatma_in_progress' using errcode = '22023';
    end if;
    update public.khatma_groups set round_reason = v_reason, round_dedication = v_dedication where id = p_group;
  end if;

  insert into public.group_calls (group_id, sender_id, kind, reason, dedication, round, expires_at)
  values (p_group, v_user, p_kind, v_reason, v_dedication,
          case when p_kind = 'khatma' then v_group.round end,
          now() + case when p_kind = 'khatma' then interval '30 days' else interval '24 hours' end)
  returning id into v_id;
  return v_id;
end $$;

-- Answer a call. Salawat / istighfar add p_count (1..1000 per tap batch) to my total; every other
-- kind is a single "done". Returns the call's new totals.
create or replace function public.respond_group_call(p_call bigint, p_count int default 1) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_call public.group_calls;
  v_user uuid;
  v_add int;
begin
  select * into v_call from public.group_calls where id = p_call;
  if v_call.id is null then raise exception 'community:not_found' using errcode = '22023'; end if;
  v_user := public._khatma_require_member(v_call.group_id);
  if v_call.kind = 'khatma_done' then raise exception 'community:invalid_call' using errcode = '22023'; end if;
  if v_call.expires_at <= now() then raise exception 'community:call_expired' using errcode = '22023'; end if;
  if v_call.kind in ('salawat', 'istighfar') then
    v_add := least(greatest(coalesce(p_count, 1), 1), 1000);
    insert into public.group_call_responses (call_id, user_id, count) values (p_call, v_user, v_add)
    on conflict (call_id, user_id) do update
      set count = least(public.group_call_responses.count + excluded.count, 100000), updated_at = now();
  else
    insert into public.group_call_responses (call_id, user_id, count) values (p_call, v_user, 1)
    on conflict (call_id, user_id) do nothing;
  end if;
  return (
    select jsonb_build_object('total', coalesce(sum(count), 0), 'responders', count(*),
                              'mine', coalesce(sum(count) filter (where user_id = v_user), 0))
    from public.group_call_responses where call_id = p_call
  );
end $$;

create or replace function public._group_call_json(p_id bigint, p_viewer uuid) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id', c.id, 'group_id', c.group_id, 'sender_id', c.sender_id,
    'sender_name', (select display_name from public.khatma_members where group_id = c.group_id and user_id = c.sender_id),
    'kind', c.kind, 'reason', c.reason, 'dedication', c.dedication, 'round', c.round,
    'created_at', c.created_at, 'expires_at', c.expires_at, 'open', c.expires_at > now(),
    'total', coalesce((select sum(count) from public.group_call_responses where call_id = c.id), 0),
    'responders', (select count(*) from public.group_call_responses where call_id = c.id),
    'mine', coalesce((select count from public.group_call_responses where call_id = c.id and user_id = p_viewer), 0),
    -- For a khatma call: juz' read so far in that khatma.
    'juz_done', case when c.kind = 'khatma' then
      (select count(*) from public.khatma_parts where group_id = c.group_id and round = c.round and done_at is not null) end
  )
  from public.group_calls c where c.id = p_id
$$;

-- The group's calls from the last 7 days (and the current khatma call), newest first.
create or replace function public.get_group_calls(p_group uuid) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v_user uuid := public._khatma_require_member(p_group);
begin
  return (
    select coalesce(jsonb_agg(public._group_call_json(c.id, v_user) order by c.created_at desc), '[]'::jsonb)
    from (select * from public.group_calls
          where group_id = p_group and (created_at > now() - interval '7 days' or expires_at > now())
          order by created_at desc limit 40) c
  );
end $$;

-- Open calls in all my groups that I haven't answered yet (home screen), newest first.
create or replace function public.get_my_pending_calls() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public._group_call_json(c.id, auth.uid()) || jsonb_build_object('group_name', g.name)
                            order by c.created_at desc), '[]'::jsonb)
  from (
    select c.* from public.group_calls c
    join public.khatma_members m on m.group_id = c.group_id and m.user_id = auth.uid()
    where c.expires_at > now() and c.kind <> 'khatma_done' and c.sender_id is distinct from auth.uid()
      and not exists (select 1 from public.group_call_responses r where r.call_id = c.id and r.user_id = auth.uid())
    order by c.created_at desc limit 20
  ) c
  join public.khatma_groups g on g.id = c.group_id
$$;

-- ---------------------------------------------------------------------------
-- RPCs: weekly achievements board
-- ---------------------------------------------------------------------------
-- Each member's week starts Friday 00:00 in their own time zone (same week as the AI limits), so
-- the board resets every Friday. Ranked by XP earned this week (XP already weighs reading,
-- listening, adhkar, prayers, hifz and recitation with daily caps). Members of the group only.
create or replace function public.get_group_board(p_group uuid) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_user uuid := public._khatma_require_member(p_group);
  v_rows jsonb;
  v_champion jsonb;
begin
  with m as (
    select m.user_id, m.display_name, m.role, public._user_week_start(m.user_id) as ws, public._user_today(m.user_id) as today
    from public.khatma_members m where m.group_id = p_group
  ), stats as (
    select m.user_id, m.display_name, m.role,
      coalesce(sum(d.xp_earned) filter (where d.activity_date >= m.ws), 0) as xp_week,
      coalesce(sum(d.ayahs_read) filter (where d.activity_date >= m.ws), 0) as ayahs_week,
      coalesce(sum(d.adhkar_completed) filter (where d.activity_date >= m.ws), 0) as adhkar_week,
      coalesce(sum(d.ayahs_memorized + d.reviews_done) filter (where d.activity_date >= m.ws), 0) as hifz_week,
      coalesce(sum(d.xp_earned) filter (where d.activity_date >= m.ws - 7 and d.activity_date < m.ws), 0) as xp_last_week,
      m.ws, m.today
    from m left join public.daily_activity d on d.user_id = m.user_id and d.activity_date >= m.ws - 7
    group by m.user_id, m.display_name, m.role, m.ws, m.today
  ), full_stats as (
    select s.*,
      case when pr.last_active_date >= s.today - 1 then pr.current_streak else 0 end as streak,
      (select count(*) from public.khatma_parts p join public.khatma_groups g on g.id = p.group_id
        where p.group_id = p_group and p.round = g.round and p.done_by = s.user_id and p.done_at is not null) as juz_round,
      (select count(*) from public.group_call_responses r join public.group_calls c on c.id = r.call_id
        where c.group_id = p_group and r.user_id = s.user_id and r.created_at >= s.ws::timestamptz) as calls_week
    from stats s join public.profiles pr on pr.id = s.user_id
  )
  select
    coalesce(jsonb_agg(jsonb_build_object(
      'user_id', user_id, 'display_name', display_name, 'role', role, 'xp_week', xp_week, 'ayahs_week', ayahs_week,
      'adhkar_week', adhkar_week, 'hifz_week', hifz_week, 'streak', streak, 'juz_round', juz_round, 'calls_week', calls_week
    ) order by xp_week desc, ayahs_week desc, streak desc, display_name), '[]'::jsonb),
    (select jsonb_build_object('user_id', f2.user_id, 'display_name', f2.display_name, 'xp', f2.xp_last_week)
     from full_stats f2 where f2.xp_last_week > 0 order by f2.xp_last_week desc, f2.display_name limit 1)
  into v_rows, v_champion
  from full_stats;
  return jsonb_build_object('rows', v_rows, 'last_week_champion', v_champion,
                            'resets_at', public._user_week_resets_at(v_user));
end $$;

-- ---------------------------------------------------------------------------
-- Push notifications (FCM). The app registers its token; the group-push edge function (service
-- role) asks _group_call_push_targets() who to notify. Each call is pushed at most once.
-- ---------------------------------------------------------------------------
create or replace function public.register_push_token(p_token text, p_platform text) returns void
language plpgsql security definer set search_path = public as $$
declare v_user uuid := auth.uid();
begin
  if v_user is null then raise exception 'not authenticated'; end if;
  if p_platform not in ('ios', 'android') or char_length(coalesce(p_token, '')) not between 10 and 4096 then
    raise exception 'invalid push token' using errcode = '22023';
  end if;
  insert into public.push_tokens (token, user_id, platform) values (p_token, v_user, p_platform)
  on conflict (token) do update set user_id = excluded.user_id, platform = excluded.platform, updated_at = now();
  -- At most 5 phones per account: drop the oldest.
  delete from public.push_tokens where token in (
    select token from public.push_tokens where user_id = v_user order by updated_at desc offset 5);
end $$;

create or replace function public.unregister_push_token(p_token text) returns void
language sql security definer set search_path = public as $$
  delete from public.push_tokens where token = p_token and user_id = auth.uid()
$$;

-- Service role only. Checks that p_caller may announce this call (the sender, or any member for a
-- server-posted 'khatma_done'), marks it pushed, and returns what to send to whom.
-- Returns null when there is nothing to send (already pushed, expired, not allowed).
create or replace function public._group_call_push_targets(p_call bigint, p_caller uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_call public.group_calls;
begin
  select * into v_call from public.group_calls where id = p_call for update;
  if v_call.id is null or v_call.pushed_at is not null or v_call.expires_at <= now() then return null; end if;
  if not (v_call.sender_id is not distinct from p_caller
          or (v_call.sender_id is null and exists (select 1 from public.khatma_members
                                                   where group_id = v_call.group_id and user_id = p_caller))) then
    return null;
  end if;
  update public.group_calls set pushed_at = now() where id = p_call;
  return jsonb_build_object(
    'call_id', v_call.id, 'group_id', v_call.group_id, 'kind', v_call.kind, 'reason', v_call.reason,
    'dedication', v_call.dedication,
    'group_name', (select name from public.khatma_groups where id = v_call.group_id),
    'sender_name', (select display_name from public.khatma_members where group_id = v_call.group_id and user_id = v_call.sender_id),
    'targets', coalesce((
      select jsonb_agg(jsonb_build_object('token', t.token, 'locale', pr.locale))
      from public.khatma_members m
      join public.push_tokens t on t.user_id = m.user_id
      join public.profiles pr on pr.id = m.user_id
      where m.group_id = v_call.group_id and not m.muted and m.user_id is distinct from v_call.sender_id
        and m.user_id <> p_caller), '[]'::jsonb)
  );
end $$;

create or replace function public._drop_push_tokens(p_tokens text[]) returns void
language sql security definer set search_path = public as $$
  delete from public.push_tokens where token = any (p_tokens)
$$;

